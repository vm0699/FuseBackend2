/**
 * Canonical gift catalog data — the single source of truth shared by:
 *   - scripts/uploadGiftImages.js (sources + uploads product photos to S3)
 *   - scripts/seedGiftCatalog.js  (upserts these into GiftCatalogItem)
 *
 * `keyword` drives the Pexels image search (uploadGiftImages.js).
 * `filename` is the S3 object key under the `gifts/` prefix — both scripts
 * must agree on this exact name.
 *
 * Pricing rule: finalAmount = price + platformFee + deliveryFee.
 * Bands: LOW price <= 499, MID price 500..2999 (enforced by the model).
 */

const LOW_DELIVERY = 49;
const MID_DELIVERY = 49;

// price -> { price, platformFee, deliveryFee, finalAmount } for a LOW item
const low = (price, platformFee) => ({
  price,
  platformFee,
  deliveryFee: LOW_DELIVERY,
  finalAmount: price + platformFee + LOW_DELIVERY,
});

// price -> same for a MID item
const mid = (price, platformFee) => ({
  price,
  platformFee,
  deliveryFee: MID_DELIVERY,
  finalAmount: price + platformFee + MID_DELIVERY,
});

